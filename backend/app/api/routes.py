router = APIRouter()

DATA_PATH = Path(__file__).resolve().parent.parent.parent / "data" / "ne_india_locations.json"
GEO_DATA_PATH = Path(__file__).resolve().parent.parent.parent.parent / "frontend" / "data" / "geo_data.json"
LOCATIONS_CACHE: List[Dict[str, Any]] = []

# Fields produced by random.uniform / random.randint in seed_locations.py.
# Stripped on load so they cannot reach a response or a model input.
FABRICATED_FIELDS = (
    "risk_probability", "risk_category", "flood_risk_category",
    "key_risk_factors", "snow_cover_pct", "snowmelt_rate", "bare_soil_pct",
    "vegetation_index", "farm_change_flag", "flood_extent_flag",
    "historical_landslides", "distance_road", "distance_river", "aspect",
    "land_cover", "satellite_source", "is_sample_data",
)


def _classify_provenance(record: dict) -> str:
    """Curated sites were hand-entered; 'Sector-N' sites were generated by
    jittering a random parent's coordinates."""
    return "SYNTHETIC_SEED" if "Sector-" in record.get("name", "") else "CURATED_SEED"


def get_all_cached_locations() -> List[Dict[str, Any]]:
    global LOCATIONS_CACHE
    if not LOCATIONS_CACHE:
        cleaned = []
        seen_districts = set()

        # 1. Load field monitoring locations from ne_india_locations.json
        if DATA_PATH.exists():
            with open(DATA_PATH, "r", encoding="utf-8") as f:
                raw = json.load(f)
            for rec in raw:
                item = {k: v for k, v in rec.items() if k not in FABRICATED_FIELDS}
                item["provenance"] = _classify_provenance(rec)
                item["data_status"] = "NO_DATA"
                cleaned.append(item)
                key = (item.get("state", "").lower(), item.get("district", "").lower())
                seen_districts.add(key)

        # 2. Fold in all 726 Indian districts from geo_data.json for complete All-India coverage
        if GEO_DATA_PATH.exists():
            with open(GEO_DATA_PATH, "r", encoding="utf-8") as f:
                geo = json.load(f)
            districts = geo.get("districts", [])
            current_id = max((l["id"] for l in cleaned), default=0) + 1
            for d in districts:
                st = d.get("s", "Unknown")
                dist_name = d.get("n", "Unknown")
                key = (st.lower(), dist_name.lower())
                if key not in seen_districts:
                    lat = float(d["ll"][0]) if d.get("ll") else 20.0
                    lon = float(d["ll"][1]) if d.get("ll") else 78.0
                    tier = d.get("tier", 1)
                    item = {
                        "id": current_id,
                        "name": dist_name,
                        "district": dist_name,
                        "state": st,
                        "latitude": lat,
                        "longitude": lon,
                        "elevation": float(d.get("e", 500)),
                        "slope": float(d.get("sl", 15.0)),
                        "soil_type": d.get("soil", "Clay Loam"),
                        "geology": d.get("geo", "Sedimentary"),
                        "coverage_tier": "FULL_HAZARD_MONITORING" if tier == 1 else "SCREENING" if tier == 2 else "PLAINS",
                        "has_prediction": tier == 1,
                        "provenance": "CURATED_SEED",
                        "data_status": "NO_DATA"
                    }
                    cleaned.append(item)
                    seen_districts.add(key)
                    current_id += 1

        LOCATIONS_CACHE = cleaned
    return LOCATIONS_CACHE


def _find(loc_id: int) -> Dict[str, Any]:
    loc = next((l for l in get_all_cached_locations() if l["id"] == loc_id), None)
    if not loc:
        raise HTTPException(status_code=404, detail=f"Location ID {loc_id} not found.")
    return loc


def _envelope(payload: dict) -> dict:
    payload["advisory"] = ADVISORY_NOTICE
    payload["timestamp"] = utcnow().isoformat()
    if is_demo():
        payload["data_mode"] = DEMO_LABEL
    return payload


def _features_from(loc: dict, weather: dict, satellite: dict) -> Optional[dict]:
    """Assemble a model input vector from OBSERVED values only.

    Returns None when a required observation is missing, so the caller can
    return NO DATA instead of a score computed from absent rainfall.
    """
    observed = (weather or {}).get("observed") or {}
    if observed.get("rainfall_24h") is None:
        return None
    features = dict(loc)
    features.update({
        "rainfall_1h": observed.get("rainfall_1h") or 0.0,
        "rainfall_24h": observed.get("rainfall_24h"),
        "rainfall_7d_cumulative": observed.get("rainfall_7d_cumulative") or 0.0,
        "rainfall_intensity": observed.get("rainfall_1h") or 0.0,
    })
    for key in ("snow_cover_pct", "snowmelt_rate", "bare_soil_pct", "vegetation_index"):
        value = (satellite or {}).get(key)
        if value is not None:
            features[key] = value
    return features


def _unavailable_prediction(weather: dict, satellite: dict) -> dict:
    return {
        "hazard_index": None,
        "risk_category": None,
        "flood_index": None,
        "flood_risk_category": None,
        "key_risk_factors": None,
        "top_factors": {},
        "shap_values": {},
        "status": "NO_DATA",
        "reason": "No observed rainfall available; a hazard index is not computed "
                  "from absent inputs.",
        "inputs": {
            "weather": (weather or {}).get("data_status"),
            "satellite": (satellite or {}).get("data_status"),
        },
    }


@router.get("/locations", response_model=List[LocationResponse])
async def get_locations(state: Optional[str] = None, district: Optional[str] = None,
                        risk: Optional[str] = None):
    """Monitoring sites. Hazard attributes are withheld pending M1."""
    locs = get_all_cached_locations()
    if state:
        locs = [l for l in locs if l.get("state", "").lower() == state.lower()]
    if district:
        locs = [l for l in locs if l.get("district", "").lower() == district.lower()]
    if risk:
        # Risk filtering needs a real risk value. None exists yet.
        locs = []
    return locs


@router.get("/hierarchy", response_model=List[StateDistrictHierarchyItem])
async def get_state_district_hierarchy():
    state_map: Dict[str, Dict[str, Any]] = {}
    for loc in get_all_cached_locations():
        st = loc.get("state", "Unknown")
        dist = loc.get("district", st)
        entry = state_map.setdefault(st, {
            "districts": set(), "total_locations": 0, "hazard_monitoring_active": False,
        })
        entry["districts"].add(dist)
        entry["total_locations"] += 1
        # No location has active hazard monitoring until ingestion lands (M3/M4).
    return [
        StateDistrictHierarchyItem(
            state=st, districts=sorted(d["districts"]),
            total_locations=d["total_locations"],
            hazard_monitoring_active=d["hazard_monitoring_active"],
        )
        for st, d in sorted(state_map.items())
    ]


@router.get("/location/{loc_id}")
async def get_location_detail(loc_id: int):
    loc = _find(loc_id)
    weather = await fetch_live_weather(loc["latitude"], loc["longitude"])
    satellite = get_satellite_observation(loc)

    features = _features_from(loc, weather, satellite)
    prediction = predict_risk(features) if features else _unavailable_prediction(weather, satellite)

    return _envelope({
        "location": loc,
        "weather": weather,
        "satellite": satellite,
        "prediction": prediction,
        "threshold_alert": evaluate_threshold_breach(loc, weather, prediction),
        "disclaimer": settings.PROTOTYPE_DISCLAIMER,
    })


