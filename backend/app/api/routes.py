@router.get("/risk/{loc_id}")
async def get_location_risk(loc_id: int):
    """Joins observed weather before scoring.

    The baseline passed the bare location record to the model, so rainfall
    defaulted to 0.0 mm and the endpoint reported Low risk during rainfall it
    had simply never been given.
    """
    loc = _find(loc_id)
    weather = await fetch_live_weather(loc["latitude"], loc["longitude"])
    satellite = get_satellite_observation(loc)
    features = _features_from(loc, weather, satellite)

    if features is None:
        return _envelope({
            "location_id": loc_id, "name": loc["name"], "state": loc["state"],
            "district": loc.get("district", loc["state"]),
            **_unavailable_prediction(weather, satellite),
            "disclaimer": settings.PROTOTYPE_DISCLAIMER,
        })

    res = predict_risk(features)
    return _envelope({
        "location_id": loc_id, "name": loc["name"], "state": loc["state"],
        "district": loc.get("district", loc["state"]),
        "hazard_index": res["hazard_index"],
        "risk_category": res["risk_category"],
        "calibration": res["calibration"],
        "index_note": res["index_note"],
        "key_risk_factors": res["key_risk_factors"],
        "top_factors": res["top_factors"],
        "inputs": {"weather": weather.get("data_status"),
                   "satellite": satellite.get("data_status")},
        "disclaimer": settings.PROTOTYPE_DISCLAIMER,
    })


